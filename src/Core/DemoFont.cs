/// <summary>Builds the starter typeface that ships with the application.</summary>
/// <remarks>
/// The design is a rounded geometric monoline: every character is assembled
/// from stems, straight bands, ellipse arcs and rings. It demonstrates what a
/// finished project looks like without shipping a third-party font file, and
/// every curve remains fully editable in the glyph editor.
/// </remarks>
