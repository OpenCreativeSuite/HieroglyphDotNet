    private static void AddKerning(FontStyle style)
    {
        (string Pair, int Value)[] pairs =
        [
            ("AV", -70), ("VA", -70), ("AW", -60), ("WA", -60), ("AY", -70), ("YA", -60),
            ("AT", -70), ("TA", -70), ("To", -90), ("Ta", -80), ("Te", -70), ("Tu", -70),
            ("Ty", -70), ("Yo", -80), ("LT", -80), ("LV", -80), ("LW", -70), ("LY", -80),
            ("P.", -100), ("F.", -90), ("V.", -110), ("W.", -80), ("T.", -110), ("Y.", -110),
            ("r.", -50), ("f.", -40), ("P,", -90), ("F,", -80), ("V,", -90), ("T,", -90),
            ("PA", -50), ("FA", -40), ("VA", -70), ("WA", -50), ("YA", -60),
            ("ov", -20), ("ow", -20), ("oy", -30), ("vo", -20), ("wo", -20), ("yo", -20),
            ("rv", -20), ("ry", -20), ("cx", 0), ("Ox", -20),
        ];

        foreach ((string pair, int value) in pairs)
        {
            if (pair.Length < 2)
            {
                continue;
            }

            style.Kerning[(pair[0], pair[1])] = value;
        }
    }
