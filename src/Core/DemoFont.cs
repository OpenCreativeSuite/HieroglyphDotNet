    /// <summary>Creates the sample project.</summary>
    public static FontProject Create()
    {
        FontProject project = FontProject.Create("Occam");
        project.Version = "1.000";
        project.Designer = "Open Creative Suite";
        project.Copyright = "Sample typeface generated by Hieroglyph.NET. Yours to keep and remix.";
        project.Description = "A rounded geometric sans used as the starter project.";
        project.License = "Released with the sample project for unrestricted use.";
        project.SampleText = "The quick brown fox jumps over the lazy dog";

        FontStyle style = project.ActiveStyle;
        style.Name = "Regular";
        style.Weight = 400;
        style.Metrics = new FontMetrics
        {
            UnitsPerEm = 1000,
            Ascender = 800,
            Descender = -200,
            CapHeight = (int)Cap,
            XHeight = (int)XHeight,
        };

        Upper(style);
        Lower(style);
        Digits(style);
        Marks(style);
        AddKerning(style);
        return project;
    }

    private static void Design(FontStyle style, int code, int advance, Action<OutlineBuilder> build)
    {
        if (!style.Glyphs.TryGetValue(code, out Glyph? glyph))
        {
            glyph = Glyph.Blank(code, CharacterSet.NameFor(code), advance);
            style.Glyphs[code] = glyph;
        }

        OutlineBuilder builder = new();
        build(builder);
        glyph.Contours = [.. builder.Contours];
        glyph.AdvanceWidth = advance;
    }

